#!/usr/bin/env python3
"""png2c.py - convert indexed pixel-art PNGs into C SpriteSheet arrays.

The output matches aquarium/src/engine/sprite.h: 4 bits per pixel, high nibble
= left pixel, frames stacked vertically, palette index 0 = transparent.

Usage:
    python3 assets/tools/png2c.py fish.png --frames 4 --name fish > fish_sprite.h

A PNG with more than 16 colours (including transparency) is rejected with an
error. Requires Pillow (sudo dnf install python3-pillow).
"""
import argparse
import sys

try:
    from PIL import Image
except ImportError:
    sys.exit("error: Pillow missing (sudo dnf install python3-pillow)")


def rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("png")
    ap.add_argument("--frames", type=int, default=1, help="frames stacked vertically")
    ap.add_argument("--name", default=None, help="C identifier (default: file name)")
    args = ap.parse_args()

    img = Image.open(args.png).convert("RGBA")
    w, h = img.size
    if h % args.frames:
        sys.exit(f"error: height {h} is not a multiple of --frames {args.frames}")
    name = args.name or args.png.rsplit("/", 1)[-1].rsplit(".", 1)[0].replace("-", "_")

    # palette: index 0 reserved for transparency, then colours in order of appearance
    palette = []
    indices = []
    for y in range(h):
        for x in range(w):
            r, g, b, a = img.getpixel((x, y))
            if a < 128:
                indices.append(0)
                continue
            c = (r, g, b)
            if c not in palette:
                palette.append(c)
                if len(palette) > 15:
                    sys.exit(f"error: {args.png} uses more than 16 colours (15 + transparency); reduce the palette")
            indices.append(palette.index(c) + 1)

    stride = (w + 1) // 2
    data = bytearray(stride * h)
    for y in range(h):
        for x in range(w):
            v = indices[y * w + x]
            if x & 1:
                data[y * stride + x // 2] |= v
            else:
                data[y * stride + x // 2] |= v << 4

    out = sys.stdout
    out.write(f"// Generated by png2c.py from {args.png} - do not edit.\n#pragma once\n")
    out.write('#include "../engine/sprite.h"\n\n')
    out.write(f"static const uint16_t {name}_palette[16] = {{\n    0x0000,")
    for i, (r, g, b) in enumerate(palette):
        out.write(f" 0x{rgb565(r, g, b):04X},")
    out.write(" 0x0000," * (15 - len(palette)) + "\n};\n\n")
    out.write(f"static const uint8_t {name}_data[{len(data)}] = {{\n")
    for i in range(0, len(data), 16):
        out.write("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",\n")
    out.write("};\n\n")
    out.write(f"static const SpriteSheet {name}_sheet = {{{w}, {h // args.frames}, {args.frames}, {name}_data}};\n")


if __name__ == "__main__":
    main()
